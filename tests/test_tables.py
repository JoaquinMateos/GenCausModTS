"""Tests for the table-generation audit fixes (C6, C10, C16, C17, C18, C21)."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

_SCRIPTS = Path(__file__).resolve().parents[1] / "scripts"


def _load(name: str):
    path = _SCRIPTS / f"{name}.py"
    if name in sys.modules:
        return sys.modules[name]
    sys.path.insert(0, str(_SCRIPTS))
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def test_fmt_distinguishes_structural_na_from_pending() -> None:
    module = _load("make_paper_tables")
    aggregated = {"m": {"mcc": {"mean": 0.4, "std": 0.1}}}
    assert module._fmt(aggregated, "m", "mcc") == r"0.40\tiny{$\pm$0.10}"
    # A metric the benchmark cannot expose is n/a, not a red pending dash.
    assert module._fmt(aggregated, "m", "shd", unavailable=True) == "n/a"
    assert module._fmt(aggregated, "m", "shd") == r"\textcolor{red}{--}"


def test_case_completeness_requires_the_exact_distinct_seed_set() -> None:
    module = _load("make_paper_tables")
    base = [{"case": "iVAE", "seed": seed, "mcc": 0.1} for seed in range(5)]
    assert module._case_complete(base, "iVAE", 5)
    assert not module._case_complete(base[:4], "iVAE", 5)
    # An extra seed is a different protocol, not a larger sample.
    assert not module._case_complete(base + [{"case": "iVAE", "seed": 9}], "iVAE", 5)
    # A duplicated (case, seed) row would reweight the mean.
    assert not module._case_complete(base + [base[0]], "iVAE", 5)
    # Legacy rows without a seed keep their documented row-count fallback.
    legacy = [{"case": "real/LEAP", "mcc": 0.1} for _ in range(5)]
    assert module._case_complete(legacy, "real/LEAP", 5)


def _stats_rows(seed_count: int) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    methods = ["iVAE", "LEAP", "TDRL", "NCTRL", "MOSAIC", "CaDRe"]
    for problem in ("grid_a", "grid_b", "grid_c"):
        for index, method in enumerate(methods):
            for seed in range(seed_count):
                rows.append(
                    {
                        "case": method,
                        "dataset": problem,
                        "seed": seed,
                        "mcc": 0.5 + 0.05 * index + 0.01 * seed,
                        "r2_diag": 0.4 + 0.02 * index,
                        "r2_sep": 0.2 - 0.01 * index,
                        "forecast1": 0.1 + 0.01 * index,
                    }
                )
    return rows


def test_stats_section_reads_grid_dir_and_never_emits_a_blank_table(
    tmp_path: Path,
) -> None:
    module = _load("make_paper_tables")
    shared = tmp_path / "shared"
    grid = tmp_path / "grid"
    shared.mkdir()
    grid.mkdir()
    # A grid file in the shared directory must not be used (C6).
    (shared / "crl_shared_grid_a.json").write_text(
        json.dumps(_stats_rows(5)), encoding="utf-8"
    )
    module.write_stats_section(grid, tmp_path / "latex")
    text = (tmp_path / "latex" / "pic" / "experiments" / "stats_table.tex").read_text()
    assert "Grid statistics pending" in text
    assert "\\midrule" in text and "\\bottomrule" in text
    assert "\\textbf{Metric}" in text

    # An incomplete seed set in the grid directory is reported as pending too.
    (grid / "crl_shared_grid_a.json").write_text(
        json.dumps(_stats_rows(4)), encoding="utf-8"
    )
    module.write_stats_section(grid, tmp_path / "latex", seeds=5)
    text = (tmp_path / "latex" / "pic" / "experiments" / "stats_table.tex").read_text()
    assert "Grid statistics pending" in text


def test_stats_section_computes_tests_from_a_complete_grid(tmp_path: Path) -> None:
    module = _load("make_paper_tables")
    grid = tmp_path / "grid"
    grid.mkdir()
    (grid / "crl_shared_grid_a.json").write_text(
        json.dumps(_stats_rows(5)), encoding="utf-8"
    )
    module.write_stats_section(grid, tmp_path / "latex", seeds=5)
    text = (tmp_path / "latex" / "pic" / "experiments" / "stats_table.tex").read_text()
    assert "Grid statistics pending" not in text
    assert "Friedman" in text
    assert "% Generated by scripts/make_paper_tables.py" in text.splitlines()[1]


def _visual_rows(seeds: int) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for suite in ("causal3d_img", "pong", "pinball", "ball_in_boxes"):
        for method in ("CITRIS", "iCITRIS", "iVAE", "LEAP", "TDRL", "NCTRL"):
            for seed in range(seeds):
                rows.append(
                    {
                        "case": method,
                        "dataset": suite,
                        "seed": seed,
                        "mcc": 0.3 + 0.01 * seed,
                        "r2_diag": 0.2,
                        "r2_sep": 0.3,
                        "dci": 0.2,
                        "forecast1": 0.05,
                        "forecast4": 0.06,
                    }
                )
    return rows


_MINIMAL_TABLE = r"""\begin{table}
  \caption{test}
  \begin{tabular}{l}
    \toprule
    old \\
    \midrule
    OLD BODY \\
    \bottomrule
  \end{tabular}
\end{table}
"""


def _write_progress(directory: Path, suite: str) -> None:
    payload = {
        "stem": f"crl_shared_{suite}",
        "label": suite,
        "total": 1,
        "done": 1,
        "errors": 0,
        "started_at": 0.0,
        "updated_at": 1.0,
        "finished": True,
    }
    (directory / f"crl_shared_{suite}_progress.json").write_text(
        json.dumps(payload), encoding="utf-8"
    )


def test_visual_tables_refuse_partial_and_stamp_provenance(tmp_path: Path) -> None:
    module = _load("make_visual_tables")
    crl = tmp_path / "crl"
    latex = tmp_path / "latex"
    crl.mkdir()
    latex.mkdir()
    for name in ("visual_full.tex", "visual_results.tex"):
        (latex / name).write_text(_MINIMAL_TABLE, encoding="utf-8")
    for suite in ("causal3d_img", "pong", "pinball", "ball_in_boxes"):
        (crl / f"crl_shared_{suite}.json").write_text(
            json.dumps(_visual_rows(5)), encoding="utf-8"
        )

    # No progress records: the gate must leave the checked-in tables alone.
    assert not module.write_tables(crl, latex, require_finished=True, seeds=5)
    assert "OLD BODY" in (latex / "visual_full.tex").read_text()

    # --allow-partial writes the body but stamps the file PARTIAL.
    assert module.write_tables(
        crl, latex, require_finished=False, allow_partial=True, seeds=5
    )
    text = (latex / "visual_full.tex").read_text()
    assert "provenance: PARTIAL" in text
    assert "Causal3DIdent & CITRIS" in text

    # Finished progress records + exact seeds: the file is stamped COMPLETE.
    for suite in ("causal3d_img", "pong", "pinball", "ball_in_boxes"):
        _write_progress(crl, suite)
    assert module.write_tables(crl, latex, require_finished=True, seeds=5)
    text = (latex / "visual_full.tex").read_text()
    assert "provenance: COMPLETE" in text
    assert "provenance: PARTIAL" not in text


def test_visual_tables_fail_closed_on_a_corrupt_row_file(tmp_path: Path) -> None:
    module = _load("make_visual_tables")
    crl = tmp_path / "crl"
    crl.mkdir()
    (crl / "crl_shared_pong.json").write_text("{not json", encoding="utf-8")
    with pytest.raises(ValueError, match="Unreadable visual rows"):
        module.write_tables(crl, tmp_path, require_finished=False, seeds=5)


def test_visual_stat_requires_the_exact_seed_set() -> None:
    module = _load("make_visual_tables")
    rows = _visual_rows(5)
    subset = [row for row in rows if row["case"] == "CITRIS" and row["dataset"] == "pong"]
    assert module._stat(subset, "mcc", 5) is not None
    assert module._stat(subset[:4], "mcc", 5) is None
    assert module._stat(subset + [subset[0]], "mcc", 5) is None
