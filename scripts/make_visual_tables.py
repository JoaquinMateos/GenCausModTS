#!/usr/bin/env python3
"""Fill the visual-block LaTeX tables from the final benchmark rows.

The table captions and column specifications stay in the checked-in `.tex`
files; only the tabular body is regenerated.  Missing cells are emitted as red
placeholders, so a partially completed run cannot be mistaken for a result.

Provenance and completeness (C16/C17): every run is stamped with a LaTeX
comment header naming the source directory, the code revision and whether the
run finished, and the script refuses to touch the checked-in tables unless the
four visual suites have the exact expected seed set (``--allow-partial``
overrides that and stamps the file ``PARTIAL``).
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gcmts.evaluation.progress import read_progress  # noqa: E402
from gcmts.evaluation.report import (  # noqa: E402
    atomic_write_text,
    code_revision,
)

DATASETS = [
    ("causal3d_img", "A.4b: real Temporal Causal3DIdent (seven shapes, 64$\\times$64)", "Causal3DIdent"),
    ("pong", "A.4c: Interventional Pong (32$\\times$32)", "Pong"),
    ("pinball", "A.4d: Causal Pinball (64$\\times$64)", "Pinball"),
    ("ball_in_boxes", "A.4e: Ball-in-Boxes (32$\\times$32)", "Ball-in-Boxes"),
]
METHODS = ["CITRIS", "iCITRIS", "iVAE", "LEAP", "TDRL", "NCTRL"]
METRICS = [
    ("mcc", 3),
    ("r2_diag", 3),
    ("r2_sep", 3),
    ("dci", 3),
    ("shd", 2),
    ("triplet", 3),
    ("forecast1", 4),
    ("forecast4", 4),
]
RED = r"\textcolor{red}{--}"
#: ``n/a`` is a structural statement (the release exposes no such metric), not
#: a pending result; it is deliberately plain black, unlike the red ``--``.
NA = "n/a"


def _load(path: Path) -> list[dict[str, Any]]:
    """Load rows; a corrupt file is an error, never an empty table."""
    if not path.is_file():
        return []
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(
            f"Unreadable visual rows {path}: {error}. Restore {path}.bak or "
            "move the file aside before regenerating tables."
        ) from error
    if not isinstance(payload, list):
        raise ValueError(f"{path} must contain a JSON list of rows.")
    return payload


def _stat(
    rows: list[dict[str, Any]], metric: str, seeds: int
) -> tuple[float, float] | None:
    """Mean/std for one cell, requiring the exact expected seed set (C18)."""
    if len({row.get("seed") for row in rows}) != seeds:
        return None
    if any(row.get("seed") is None for row in rows):
        return None
    if len(rows) != seeds:  # duplicated (case, seed) rows
        return None
    if {int(row["seed"]) for row in rows} != set(range(seeds)):
        return None
    values = [
        float(row[metric])
        for row in rows
        if row.get(metric) is not None
        and isinstance(row.get(metric), (int, float))
        and math.isfinite(float(row[metric]))
    ]
    if not values:
        return None
    return float(np.mean(values)), float(np.std(values, ddof=1)) if len(values) > 1 else 0.0


def _cell(stat: tuple[float, float] | None, digits: int, *, unavailable: bool = False) -> str:
    if stat is None:
        return NA if unavailable else RED
    mean, std = stat
    return f"{mean:.{digits}f}\\tiny{{$\\pm${std:.{digits}f}}}"


def _provenance(crl_dir: Path, *, complete: bool, seeds: int) -> str:
    status = "COMPLETE" if complete else "PARTIAL"
    lines = [
        "% =====================================================================",
        "% Generated by scripts/make_visual_tables.py -- do not edit by hand.",
        f"% generated_at: {datetime.now(UTC).isoformat(timespec='seconds')}",
        f"% code_revision: {code_revision()}",
        f"% rows: {crl_dir.as_posix()}",
        f"% provenance: {status}; seeds={seeds}",
        "% =====================================================================",
    ]
    return "\n".join(lines) + "\n"


def _replace_body(path: Path, body: list[str], header: str) -> None:
    """Replace the tabular body atomically, preserving the checked-in caption."""
    text = path.read_text(encoding="utf-8")
    # Drop a previous generated header so repeated runs do not accumulate it.
    lines = text.splitlines(keepends=True)
    while lines and lines[0].startswith("%"):
        lines.pop(0)
    text = "".join(lines)
    start = text.index("\\midrule") + len("\\midrule\n")
    end = text.index("\\bottomrule")
    updated = header + text[:start] + "\n".join(body) + "\n    " + text[end:]
    atomic_write_text(path, updated)


def _rows_by_dataset(
    crl_dir: Path, seeds: int
) -> dict[str, dict[str, list[dict[str, Any]]]]:
    by_dataset: dict[str, dict[str, list[dict[str, Any]]]] = {}
    for suite, _, _ in DATASETS:
        rows = _load(crl_dir / f"crl_shared_{suite}.json")

        def belongs(row: dict[str, Any], suite: str = suite) -> bool:
            label = row.get("suite", row.get("dataset"))
            return label is None or str(label) == suite

        by_dataset[suite] = {
            method: [
                row
                for row in rows
                if belongs(row)
                and (row.get("case") == method or row.get("method") == method)
            ]
            for method in METHODS
        }
    return by_dataset


def _completion_problems(
    by_dataset: dict[str, dict[str, list[dict[str, Any]]]],
    crl_dir: Path,
    seeds: int,
) -> list[str]:
    problems: list[str] = []
    expected = set(range(seeds))
    for suite, _, _ in DATASETS:
        progress = read_progress(crl_dir / f"crl_shared_{suite}_progress.json")
        if progress is None or not progress.finished or progress.errors:
            detail = "no/unreadable progress record" if progress is None else (
                f"{progress.done}/{progress.total}, errors={progress.errors}, "
                f"finished={progress.finished}"
            )
            problems.append(f"{suite}: {detail}")
        for method in METHODS:
            rows = by_dataset[suite][method]
            observed = {
                int(row["seed"]) for row in rows if row.get("seed") is not None
            }
            if observed != expected or len(rows) != seeds:
                problems.append(
                    f"{suite}/{method}: seeds {sorted(observed)[:6]} "
                    f"({len(rows)} rows), expected 0..{seeds - 1}"
                )
    return problems


def write_tables(
    crl_dir: Path,
    latex_dir: Path,
    *,
    require_finished: bool = True,
    allow_partial: bool = False,
    seeds: int = 5,
) -> bool:
    """Write ``visual_full.tex`` and ``visual_results.tex``.

    Returns ``False`` without touching any file when the completeness gate
    fails.  ``require_finished`` is ignored when ``allow_partial`` is true, in
    which case the written files are stamped ``PARTIAL``.
    """
    crl_dir = Path(crl_dir)
    experiments = Path(latex_dir)
    by_dataset = _rows_by_dataset(crl_dir, seeds)
    problems = _completion_problems(by_dataset, crl_dir, seeds)
    complete = not problems
    if require_finished and not allow_partial and problems:
        print(
            "visual tables left unchanged: the visual run is not complete "
            "(pass --allow-partial to write a PARTIAL table):\n  - "
            + "\n  - ".join(problems[:12])
            + ("" if len(problems) <= 12 else f"\n  ... and {len(problems) - 12} more")
        )
        return False

    full_path = experiments / "visual_full.tex"
    summary_path = experiments / "visual_results.tex"
    if not full_path.is_file() or not summary_path.is_file():
        print(f"missing {full_path.name}/{summary_path.name}; nothing written")
        return False

    header = _provenance(crl_dir, complete=complete, seeds=seeds)
    body: list[str] = []
    for suite, title, label in DATASETS:
        body.append(f"    \\multicolumn{{10}}{{@{{}}l}}{{\\emph{{{title}}}}}\\\\")
        for method in METHODS:
            cells = [
                _cell(
                    _stat(by_dataset[suite][method], metric, seeds),
                    digits,
                    unavailable=(
                        metric == "shd"
                        or (metric == "triplet" and suite in {"causal3d_img", "pinball"})
                    ),
                )
                for metric, digits in METRICS
            ]
            body.append(f"    {label} & {method} & " + " & ".join(cells) + " \\\\")
        if suite != DATASETS[-1][0]:
            body.append("    \\cmidrule(l){1-10}")
    _replace_body(full_path, body, header)

    body = []
    for method in METHODS:
        cells = []
        for metric, digits in METRICS:
            stats = [
                stat
                for suite, _, _ in DATASETS
                if (stat := _stat(by_dataset[suite][method], metric, seeds)) is not None
            ]
            if not stats:
                cells.append(NA if metric == "shd" else RED)
            else:
                cells.append(
                    _cell(
                        (
                            float(np.mean([stat[0] for stat in stats])),
                            float(np.mean([stat[1] for stat in stats])),
                        ),
                        digits,
                    )
                )
        body.append(f"    {method} & " + " & ".join(cells) + " \\\\")
    _replace_body(summary_path, body, header)
    print("wrote visual_results.tex and visual_full.tex")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Fill the visual-block LaTeX tables from the final rows."
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("outputs_final_v5"),
        help="CRL tree containing crl_shared_{causal3d_img,pong,pinball,ball_in_boxes}.json",
    )
    parser.add_argument(
        "--latex-dir", type=Path, default=Path("../latex/pic/experiments")
    )
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument(
        "--allow-partial",
        action="store_true",
        default=False,
        help="write a PARTIAL table from an unfinished run instead of refusing",
    )
    parser.add_argument(
        "--require-finished",
        action="store_true",
        default=True,
        help="refuse to overwrite the tables unless all visual runs finished (default)",
    )
    args = parser.parse_args()
    wrote = write_tables(
        args.out_dir,
        args.latex_dir,
        require_finished=bool(args.require_finished) and not args.allow_partial,
        allow_partial=args.allow_partial,
        seeds=args.seeds,
    )
    return 0 if wrote else 2


if __name__ == "__main__":
    raise SystemExit(main())
