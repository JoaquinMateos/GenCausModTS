_DETERMINISTIC_CASES = frozenset({"Persistence", "AR(1)"})


def _case_seed_status(
    rows: list[dict[str, Any]], case: str, seeds: int
) -> tuple[bool, str]:
    """Completeness of one case under the exact-distinct-seed rule (C18).

    Learned methods must have exactly seeds ``0 .. seeds-1``, each once; a row
    count cannot distinguish a duplicated seed (which would reweight the mean)
    or an extra seed from a different protocol.  Rows written before the seed
    was recorded (real panels, see C24) fall back to the legacy row count with
    an explicit "unverified" reason.
    """
    if case.split("/", 1)[-1] in _DETERMINISTIC_CASES:
        count = sum(1 for row in rows if row.get("case") == case)
        return (count >= 1, "" if count else f"{case}: no rows")
    selected = [row for row in rows if row.get("case") == case]
    if not selected:
        return False, f"{case}: no rows"
    if all(row.get("seed") is None for row in selected):
        # Legacy real-panel rows carry no seed; keep the row-count gate but
        # report why it is weaker than the exact-seed gate.
        return (
            len(selected) >= seeds,
            "" if len(selected) >= seeds else f"{case}: {len(selected)}/{seeds} rows",
        )
    return exact_seed_status(rows, case, seeds)


def _case_complete(rows: list[dict[str, Any]], case: str, seeds: int) -> bool:
    """True when ``case`` has the exact expected seed set (see C18)."""
    return _case_seed_status(rows, case, seeds)[0]


