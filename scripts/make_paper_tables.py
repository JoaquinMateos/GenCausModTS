def _progress_status(path: Path) -> tuple[bool, str]:
    """Whether the run that writes ``path`` finished cleanly.

    Missing/unreadable progress records fail the gate: a table built from a
    tree with no completion marker cannot be shown to be final.
    """
    if not path.exists():
        return False, f"{path.name}: no progress record"
    snapshot = read_progress(path)
    if snapshot is None:
        return False, f"{path.name}: unreadable progress record"
    if not snapshot.finished:
        return False, f"{path.name}: {snapshot.done}/{snapshot.total} runs, not finished"
    if snapshot.errors:
        return False, f"{path.name}: {snapshot.errors} failed run(s)"
    return True, ""


